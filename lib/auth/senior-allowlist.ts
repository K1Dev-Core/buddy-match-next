export const seniorAllowlist = new Set(
  rawSeniorIds
    .split("\n")
    .map((item) => item.trim())
    .filter(Boolean),
);

export async function isAllowedSeniorEmail(
  email: string,
  supabase?: SupabaseClient,
): Promise<boolean> {
  const normalized = email.trim().toLowerCase();

  if (!normalized.endsWith("@msu.ac.th")) {
    return false;
  }

  const localPart = normalized.replace("@msu.ac.th", "");

  if (seniorAllowlist.has(localPart)) return true;

  if (supabase) {
    try {
      const { data } = await supabase
        .from("senior_allowlist")
        .select("id")
        .eq("id", localPart)
        .maybeSingle();
      if (data) return true;
    } catch {}
  }

  return false;
}
